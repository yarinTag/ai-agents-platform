export type WorkflowSettingsText = typeof en;

/** Replace `{key}` placeholders; unknown keys are left untouched. */
export const formatWorkflowSettingsText = (template: string, params: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (match, key: string) => (key in params ? String(params[key]) : match));

export function useWorkflowSettingsText(): WorkflowSettingsText {
  const { locale } = useTranslation();
  return locale === 'he' ? he : en;
}
