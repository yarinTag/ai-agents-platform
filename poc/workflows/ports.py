"""Narrow storage/notification contracts consumed by workflow execution."""

from typing import Any, Dict, List, Optional, Protocol
from runtime.models import AgentRun
from storage.records import Workflow, WorkflowExecution


class WorkflowStore(Protocol):
    def get_workflow(self, workflow_id: str) -> Optional[Workflow]: ...
    def create_workflow_execution(self, **kwargs: Any) -> WorkflowExecution: ...
    def get_workflow_execution(self, execution_id: str) -> Optional[WorkflowExecution]: ...
    def update_workflow_execution(self, execution_id: str, **kwargs: Any) -> Optional[WorkflowExecution]: ...
    def check_department_budget(self, department_id: str, **kwargs: Any) -> Dict[str, Any]: ...
    def check_department_mcp_permission(self, department_id: str, connector_id: str,
                                        tool_name: Optional[str] = None) -> Dict[str, Any]: ...
    def get_agent(self, agent_id: str) -> Any: ...
    def list_agents(self, **kwargs: Any) -> List[Any]: ...
    def save_agent(self, agent: Any) -> None: ...
    def save_task_run(self, run: AgentRun) -> None: ...
    def get_task_run(self, task_id: str) -> Optional[AgentRun]: ...
    def save_workflow_step_run(self, record: Dict[str, Any]) -> None: ...


class WorkflowNotifications(Protocol):
    def notify(self, workflow_id: str, execution_id: str, trigger_type: str, status: str,
               outputs: Dict[str, str], input_tokens: int, output_tokens: int,
               cost: float, error: Optional[str]) -> None: ...
