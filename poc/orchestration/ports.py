"""Storage and event capabilities consumed by orchestration use cases.

Implementations are injected; these contracts do not import the global database
or concrete process/runtime implementation.
"""
from typing import Any, Dict, List, Optional, Protocol


try:
    from config import AgentConfig, ProjectConfig
    from runtime.models import AgentRun, TaskStatus
except ImportError:
    from poc.config import AgentConfig, ProjectConfig
    from poc.runtime.models import AgentRun, TaskStatus


class TaskStore(Protocol):
    def get_agent(self, agent_id: str) -> Optional[AgentConfig]: ...
    def get_task_run(self, run_id: str) -> Optional[AgentRun]: ...
    def save_task_run(self, run: AgentRun) -> None: ...
    def get_subtasks(self, parent_task_id: str) -> List[AgentRun]: ...
    def get_task_tree(self, root_task_id: str) -> Dict[str, Any]: ...
    def count_active_subtasks_for_parent(self, parent_agent_id: str) -> int: ...
    def list_task_runs(
        self, agent_id: Optional[str] = None, project_id: Optional[str] = None,
        status: Optional[TaskStatus] = None, limit: int = 100,
        organization_id: Optional[str] = None,
    ) -> List[AgentRun]: ...
    def claim_waiting_parent(self, parent_task_id: str) -> bool: ...


class EventEmitter(Protocol):
    def emit(self, *, event_type: Any, payload: Dict[str, Any], source: str, **kwargs: Any) -> Any: ...


class SupervisorStore(Protocol):
    def get_agent(self, agent_id: str) -> Optional[AgentConfig]: ...
    def get_task_run(self, run_id: str) -> Optional[AgentRun]: ...
    def get_interaction(self, interaction_id: str) -> Optional[Dict[str, Any]]: ...
    def create_interaction(self, interaction_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def update_task_run(self, run_id: str, **kwargs: Any) -> Optional[AgentRun]: ...
    def resolve_interaction(self, interaction_id: str, **kwargs: Any) -> Any: ...
    def get_super_agent_for_project(self, project_id: str) -> Any: ...
    def list_project_memories(self, project_id: str, **kwargs: Any) -> List[Dict[str, Any]]: ...
    def save_agent_message(self, message: Any) -> Any: ...
    def get_or_create_channel(
        self, agent_a_id: str, agent_b_id: str, task_id: str, **kwargs: Any,
    ) -> Dict[str, Any]: ...
    def save_chat_message(self, message_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def retarget_interaction(self, interaction_id: str, target_approver_id: str) -> None: ...


class HierarchyStore(Protocol):
    def get_agent(self, agent_id: str) -> Optional[AgentConfig]: ...
    def get_child_agents(self, parent_id: str) -> List[AgentConfig]: ...


class IntelligenceStore(Protocol):
    def get_project(self, project_id: str) -> Optional[ProjectConfig]: ...
    def list_project_memories(self, project_id: str, **kwargs: Any) -> List[Dict[str, Any]]: ...
    def list_task_runs(self, **kwargs: Any) -> List[AgentRun]: ...


class TeamStore(Protocol):
    def get_agent(self, agent_id: str) -> Optional[AgentConfig]: ...
    def create_agent_team(self, team_data: Dict[str, Any]) -> Any: ...
    def get_agent_team(self, team_id: str) -> Any: ...
    def update_agent_team(self, team_id: str, **kwargs: Any) -> Any: ...
    def save_task_run(self, run: AgentRun) -> None: ...
    def get_task_run(self, run_id: str) -> Optional[AgentRun]: ...
